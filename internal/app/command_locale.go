func commandLabel(id string) string {
	if suffix, ok := strings.CutPrefix(id, "tab.select"); ok {
		if suffix == "Last" {
			if key := commandMessages[id]; key != "" {
				return locales.Catalog.Format(i18n.Locale(), key, nil)
			}
		} else if n, err := strconv.Atoi(suffix); err == nil {
			return locales.CommandSelectTab(n)
		}
	}
	if key := commandMessages[id]; key != "" {
		return locales.Catalog.Format(i18n.Locale(), key, nil)
	}
	return id
}
